"""Generate the operator registry, the builder API and the reference docs.

Everything this module writes is derived from a single introspection pass over
the installed SNAP, and everything it writes is committed to the repository:

``snap_ops/operators.json``
    The full 439-operator snapshot.  Validation and codegen read this, so
    neither needs the JVM.
``snap_ops/op_funcs.py``
    Typed builder methods for the SAR-relevant operators.
``docs/operators.md``
    Human-readable parameter reference.

Run it with ``radar-snap gen-registry`` after upgrading SNAP.
"""

from __future__ import annotations

import json
import keyword
import math
import re
import shutil
import subprocess
import textwrap
from pathlib import Path

from radar_snap_lib.snap_ops.registry import (
    REGISTRY_PATH,
    OperatorSpec,
    ParamSpec,
    Registry,
    introspect_all,
    registry_to_json,
    snap_version,
)

__all__ = [
    "generate_all",
    "method_name",
    "write_docs",
    "write_op_funcs",
    "write_registry",
]

OP_FUNCS_PATH = Path(__file__).with_name("op_funcs.py")

BANNER = "# Generated by `radar-snap gen-registry`. Do not edit by hand."

#: Splits camelCase and acronym boundaries: BandMaths -> Band_Maths,
#: SARSim -> SAR_Sim, while leaving TOPSAR intact.
_CAMEL_BOUNDARY = re.compile(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])")


def method_name(alias: str) -> str:
    """Python method name for a SNAP operator alias.

    ``Terrain-Correction`` -> ``terrain_correction``,
    ``TOPSAR-Split`` -> ``topsar_split``, ``BandMaths`` -> ``band_maths``.
    """
    name = re.sub(r"[-. ]+", "_", alias)
    name = _CAMEL_BOUNDARY.sub("_", name)
    return re.sub(r"_+", "_", name).lower().strip("_")


def arg_name(param: str) -> str:
    """Python argument name for a SNAP parameter name.

    Only ``RPCA-Change-Detection.lambda`` needs escaping, but the rule is
    general: a trailing underscore avoids the keyword clash.
    """
    return f"{param}_" if keyword.iskeyword(param) else param


def _literal(value: object) -> str:
    """Python source for a default value.

    This is where the old ``SnappyNodeCreator`` went wrong: it printed SNAP's
    raw metadata strings, producing ``demName=SRTM 3Sec`` instead of
    ``demName="SRTM 3Sec"`` and ``true`` instead of ``True``.

    ``repr`` covers every case except non-finite floats, whose reprs (``nan``,
    ``inf``) are not valid Python expressions.
    """
    if isinstance(value, float) and not math.isfinite(value):
        if math.isnan(value):
            return 'float("nan")'
        return 'float("inf")' if value > 0 else 'float("-inf")'
    if isinstance(value, tuple):
        return "(" + "".join(f"{_literal(item)}, " for item in value) + ")"
    return repr(value)


def _clean(text: str) -> str:
    """Collapse a SNAP description into a single safe docstring line."""
    return " ".join(text.split()).replace("\\", "/").replace('"""', "'''")


