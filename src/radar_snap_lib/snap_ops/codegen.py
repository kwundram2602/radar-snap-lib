def _signature_parts(spec: OperatorSpec) -> tuple[list[str], str, list[str]]:
    """Build the source arguments, the ``_add`` source expression, and the pops.

    Returns ``(positional_source_args, sources_expression, names_to_pop)``.
    """
    if spec.takes_source_array:
        return ["*sources: NodeRef"], "sources", ["sources"]

    named = [src for src in spec.sources if not src.is_array]
    if not named:
        return [], "()", []
    if len(named) == 1:
        return ["source: NodeRef"], "[source]", ["source"]

    args: list[str] = []
    pops: list[str] = []
    for index, src in enumerate(named):
        name = method_name(src.name) if index else "source"
        pops.append(name)
        args.append(
            f"{name}: NodeRef | None = None" if src.optional else f"{name}: NodeRef"
        )
    return args, "[" + ", ".join(pops) + "]", pops


def _param_args(spec: OperatorSpec) -> tuple[list[str], list[str]]:
    """Split parameters into required (positional) and optional (keyword-only)."""
    required: list[str] = []
    optional: list[str] = []
    for param in spec.params.values():
        annotation = param.python_type
        name = arg_name(param.name)
        if param.required:
            required.append(f"{name}: {annotation}")
        else:
            optional.append(f"{name}: {annotation} = {_literal(param.default)}")
    return required, optional


def _docstring(spec: OperatorSpec) -> list[str]:
    summary = _clean(spec.description or f"SNAP operator {spec.alias}.")
    if not summary.endswith("."):
        summary += "."

    # SNAP descriptions run to arbitrary length; wrap so the generated module
    # stays within the project's line limit.
    wrapped = textwrap.wrap(summary, width=72) or [summary]
    lines = [f'    """{wrapped[0]}']
    lines.extend(f"    {line}" for line in wrapped[1:])
    lines.append("")
    lines.append(f"    SNAP operator: ``{spec.alias}``")

    constrained = [p for p in spec.params.values() if p.value_set]
    if constrained:
        lines.append("")
        lines.append("    Constrained parameters:")
        for param in constrained:
            allowed = " | ".join(param.value_set)
            wrapped = textwrap.wrap(
                f"{param.name}: {allowed}",
                width=76,
                initial_indent="        ",
                subsequent_indent="            ",
            )
            lines.extend(wrapped)
    lines.append('    """')
    return lines


def _render_method(spec: OperatorSpec) -> str:
    source_args, sources_expr, source_pops = _signature_parts(spec)
    required, optional = _param_args(spec)

    args = ["self", *source_args, *required]
    if optional:
        if not any(a.startswith("*") for a in source_args):
            args.append("*")
        args.extend(optional)

    lines = [f"def {method_name(spec.alias)}("]
    lines.extend(f"    {arg}," for arg in args)
    lines.append(") -> NodeRef:")
    lines.extend(_docstring(spec))

    lines.append("    params = dict(locals())")
    for name in ("self", *source_pops):
        lines.append(f'    params.pop("{name}")')
    for param in spec.params.values():
        escaped = arg_name(param.name)
        if escaped != param.name:
            lines.append(f'    params["{param.name}"] = params.pop("{escaped}")')
    lines.append(f"    return self._add({spec.alias!r}, {sources_expr}, params)")

    return textwrap.indent("\n".join(lines), "    ")


def write_op_funcs(registry: Registry, *, path: Path = OP_FUNCS_PATH) -> Path:
    """Write the typed builder mixin for the SAR-relevant operators."""
    specs = [spec for spec in registry.values() if spec.is_sar]

    seen: dict[str, str] = {}
    for spec in specs:
        name = method_name(spec.alias)
        if name in seen:
            raise RuntimeError(
                f"Method name collision: {spec.alias!r} and {seen[name]!r} "
                f"both map to {name!r}"
            )
        seen[name] = spec.alias

    header = f'''{BANNER}
"""Typed builder methods for the SAR-relevant SNAP operators.

{len(specs)} of the {len(registry)} operators SNAP exposes get a method here: the
radar, core-GPF, polarimetry, InSAR and DEM ones. The rest are optical and stay
reachable through :meth:`Graph.node`.

Every method appends a node and returns a :class:`NodeRef`; nothing executes
until :meth:`Graph.run`. Parameters SNAP marks as required are positional, the
rest are keyword-only with SNAP's own default.
"""

from __future__ import annotations

from typing import Any

from radar_snap_lib.snap_ops.nodes import NodeRef

__all__ = ["OpFuncs"]


class OpFuncs:
    """Mixin adding one builder method per SAR-relevant SNAP operator."""

    _add: Any
'''

    body = "\n\n".join(_render_method(spec) for spec in specs)
    path.write_text(f"{header}\n{body}\n", encoding="utf-8")
    _format(path)
    return path


def _format(path: Path) -> None:
    """Run ruff over a generated file so its output is stable and lint-clean."""
    ruff = shutil.which("ruff")
    if ruff is None:  # pragma: no cover - ruff is a dev dependency
        return
    subprocess.run([ruff, "check", "--fix", "--quiet", str(path)], check=False)
    subprocess.run([ruff, "format", "--quiet", str(path)], check=False)


