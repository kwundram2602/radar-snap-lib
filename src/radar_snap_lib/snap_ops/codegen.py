def _docs_root() -> Path:
    return Path(__file__).resolve().parents[3] / "docs"


def _param_row(param: ParamSpec) -> str:
    default = "" if param.default is None else f"`{param.default}`"
    values = " / ".join(f"`{v}`" for v in param.value_set) if param.value_set else ""
    flags = []
    if param.required:
        flags.append("**required**")
    if param.alias:
        flags.append(f"alias `{param.alias}`")
    notes = ", ".join(flags)
    description = _clean(param.description or "")
    detail = " ".join(part for part in (values, notes, description) if part)
    return f"| `{param.name}` | `{param.type}` | {default} | {detail} |"


def _operator_section(spec: OperatorSpec) -> str:
    lines = [f"### `{spec.alias}`", ""]
    if spec.description:
        lines.extend([_clean(spec.description), ""])
    lines.append(f"- Class: `{spec.cls}`")
    lines.append(
        f"- Builder: `Graph.{method_name(spec.alias)}()`"
        if spec.is_sar
        else f'- Builder: `Graph.node("{spec.alias}", ...)`'
    )

    if spec.takes_source_array:
        lines.append("- Sources: any number (`sourceProducts`)")
    elif spec.sources:
        names = ", ".join(
            f"`{s.name}`{' (optional)' if s.optional else ''}" for s in spec.sources
        )
        lines.append(f"- Sources: {names}")
    else:
        lines.append("- Sources: none")
    lines.append("")

    if spec.params:
        lines.append("| Parameter | Type | Default | Notes |")
        lines.append("| --- | --- | --- | --- |")
        lines.extend(_param_row(param) for param in spec.params.values())
    else:
        lines.append("_No parameters._")
    lines.append("")
    return "\n".join(lines)


def write_docs(registry: Registry, *, path: Path | None = None, version: str) -> Path:
    """Write the Markdown operator reference."""
    path = path or (_docs_root() / "operators.md")
    path.parent.mkdir(parents=True, exist_ok=True)

    sar = [spec for spec in registry.values() if spec.is_sar]
    other = [spec for spec in registry.values() if not spec.is_sar]
    total_params = sum(len(spec.params) for spec in registry.values())

    lines = [
        "<!-- Generated by `radar-snap gen-registry`. Do not edit by hand. -->",
        "",
        "# SNAP Operator Reference",
        "",
        f"SNAP {version} - {len(registry)} operators, {total_params} parameters.",
        "",
        f"{len(sar)} operators have a generated builder method on `Graph`; the "
        f"remaining {len(other)} are reachable via `Graph.node(alias, ...)`.",
        "",
        "## SAR, core GPF, polarimetry, InSAR and DEM operators",
        "",
    ]
    lines.extend(_operator_section(spec) for spec in sar)
    lines.extend(["## Remaining operators", ""])
    lines.extend(_operator_section(spec) for spec in other)

    path.write_text("\n".join(lines), encoding="utf-8")
    return path


# --------------------------------------------------------------------------- #


def generate_all() -> dict[str, Path]:
    """Introspect SNAP and regenerate every derived artifact."""
    version = snap_version()
    registry = introspect_all()
    return {
        "registry": write_registry(registry, version=version),
        "op_funcs": write_op_funcs(registry),
        "docs": write_docs(registry, version=version),
    }
